'use strict';
/* Builds src/renderer/icons.js from Lucide (lucide-static, ISC licence), so the app has one drawn icon set.
   To add an icon: find its name at https://lucide.dev/icons, add it to NAMES, run `npm run icons`, commit both files.
   Never use emoji or Unicode glyphs as icons (see the vault note "Notes App - Design System"). */
const fs = require('fs');
const path = require('path');

const NAMES = [
  // layout and navigation
  'panel-left', 'list', 'columns-2', 'ellipsis', 'search', 'command', 'x', 'plus', 'minus',
  'chevron-right', 'chevron-left', 'chevron-down', 'arrow-up', 'arrow-down', 'external-link',
  // notes and organising
  'square-pen', 'folder-open', 'notebook-text', 'star', 'bell', 'trash-2', 'folder', 'folder-plus', 'book-open',
  'book-plus', 'hash', 'file-text', 'copy', 'rotate-ccw', 'history', 'link', 'pin',
  // tools
  'code-xml', 'volume-2', 'mic', 'lock', 'lock-open', 'alarm-clock', 'paperclip', 'audio-lines', 'printer',
  'sticky-note', 'bot', 'download', 'share-2', 'replace', 'refresh-cw', 'file-output', 'terminal', 'radio',
  'sun-moon', 'settings', 'check', 'circle-alert', 'save',
  // documents
  'eye', 'highlighter', 'type', 'pencil', 'image', 'signature', 'message-square', 'layout-grid', 'undo-2', 'redo-2',
  'zoom-in', 'rotate-cw', 'bold', 'italic', 'underline', 'square-stack',
];

const pkg = path.dirname(require.resolve('lucide-static/package.json'));
const version = require('lucide-static/package.json').version;
const out = {};
for (const name of NAMES) {
  const svg = fs.readFileSync(path.join(pkg, 'icons', name + '.svg'), 'utf8');
  const inner = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(svg)[1].replace(/\s*\n\s*/g, '').trim();
  out[name] = inner;
}
const file = path.join(__dirname, '..', 'src', 'renderer', 'icons.js');
fs.writeFileSync(file, `'use strict';
/* Generated by scripts/make-icons.js from lucide-static ${version} (ISC licence, Copyright (c) Lucide Icons and
   Contributors). Do not edit by hand: add names there and run \`npm run icons\`.

   NotesIcons.svg(name) returns an <svg> string: 16px, currentColor, 1.75 stroke.
   NotesIcons.hydrate(root) puts the icon named by data-icon="..." at the start of every such element under root. */
(function () {
  const PATHS = ${JSON.stringify(out, null, 2)};
  function svg(name, size) {
    const body = PATHS[name];
    if (!body) throw new Error('Unknown icon: ' + name);
    const s = size || 16;
    return '<svg class="icon" width="' + s + '" height="' + s + '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' + body + '</svg>';
  }
  function hydrate(root) {
    (root || document).querySelectorAll('[data-icon]').forEach((el) => {
      const first = el.firstElementChild;
      if (first && first.classList.contains('icon') && first.dataset.name === el.dataset.icon) return;
      if (first && first.classList.contains('icon')) first.remove();
      el.insertAdjacentHTML('afterbegin', svg(el.dataset.icon));
      el.firstElementChild.dataset.name = el.dataset.icon;
    });
  }
  const api = { svg, hydrate, names: Object.keys(PATHS) };
  if (typeof module === 'object' && module.exports) module.exports = api;
  else window.NotesIcons = api;
})();
`);
console.log('wrote ' + file + ' (' + NAMES.length + ' icons)');
